<?php

declare(strict_types=1);

// Reproducible allowlist: excludes runtime user files, private documents and PHP pages.
$public = dirname(__DIR__) . '/public';
$assets = [];
foreach (['assets/js', 'assets/css', 'assets/images', 'assets/logos', 'assets/pwa', 'template/assets'] as $directory) {
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($public . '/' . $directory, FilesystemIterator::SKIP_DOTS));
    foreach ($iterator as $file) {
        if (!$file->isFile() || $file->isLink() || !preg_match('/\.(?:css|js|png|jpe?g|gif|webp|svg|ico|woff2?|ttf|eot)$/i', $file->getFilename())) continue;
        $path = substr($file->getPathname(), strlen($public));
        $assets[$path] = hash_file('sha256', $file->getPathname());
    }
}
foreach (['offline.html', 'manifest.webmanifest'] as $path) $assets['/' . $path] = hash_file('sha256', $public . '/' . $path);
ksort($assets);
$version = substr(hash('sha256', json_encode($assets) . file_get_contents($public . '/service-worker.js')), 0, 16);
$content = "// Generated by php bin/build-pwa.php. Rebuild after changing static assets.\n";
$content .= 'const SICRAT_STATIC_VERSION = ' . json_encode($version) . ";\n";
$content .= 'const SICRAT_STATIC_ASSETS = ' . json_encode($assets, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . ";\n";
file_put_contents($public . '/pwa-assets.js', $content);
echo count($assets) . " public assets; version " . $version . PHP_EOL;
